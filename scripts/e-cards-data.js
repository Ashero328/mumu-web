// 依「前綴＋補零位數」把數量展開成款號：ENY ＋ 4 位 ＋ 第 11 款 → ENY0011
function 展開款號(規則, 前綴, 位數, 數量) {
  var out = [];
  for (var i = 1; i <= 數量; i++) {
    out.push(前綴 + String(i).padStart(位數, "0"));
  }
  return out;
}

